import React, { useState } from 'react';
import { useNavigate, useLocation } from 'react-router-dom';
import { ShieldCheck, ArrowRight, AlertCircle } from 'lucide-react';
import { useAuth } from '@/app/providers/AuthContext';
import { useToast } from '@/app/providers/ToastContext';
import { formatApiError } from '@/lib/api/client';

export const MfaVerifyPage: React.FC = () => {
  const [code, setCode] = useState('');
  const [submitting, setSubmitting] = useState(false);
  const [errorMessage, setErrorMessage] = useState<string | null>(null);

  const { verifyMfa } = useAuth();
  const { success } = useToast();
  const navigate = useNavigate();
  const location = useLocation();

  const preAuthToken = (location.state as any)?.preAuthToken;
  const email = (location.state as any)?.email;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setErrorMessage(null);

    const cleanCode = code.trim().replace(/\s/g, '');
    if (cleanCode.length !== 6) {
      setErrorMessage('Please enter the 6-digit verification code from your authenticator app.');
      return;
    }

    setSubmitting(true);
    try {
      const res = await verifyMfa({
        token: cleanCode,
        preAuthToken,
      });

      success('Multi-factor authentication verified.');
      if (res.user.role === 'DOCTOR') {
        navigate('/doctor/dashboard', { replace: true });
      } else if (res.user.role === 'ADMIN') {
        navigate('/admin/dashboard', { replace: true });
      } else {
        navigate('/patient/dashboard', { replace: true });
      }
    } catch (err) {
      setErrorMessage(formatApiError(err));
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div
      style={{
        padding: '4rem 1.5rem',
        minHeight: '80vh',
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        backgroundColor: 'var(--am-bg)',
      }}
    >
      <div
        className="am-card"
        style={{
          maxWidth: '440px',
          width: '100%',
          padding: '2.5rem',
          boxShadow: 'var(--am-shadow-lg)',
          textAlign: 'center',
        }}
      >
        <div
          style={{
            width: '52px',
            height: '52px',
            borderRadius: '50%',
            backgroundColor: 'var(--am-primary-light)',
            color: 'var(--am-primary)',
            display: 'inline-flex',
            alignItems: 'center',
            justifyContent: 'center',
            marginBottom: '1.25rem',
          }}
        >
          <ShieldCheck size={28} />
        </div>

        <h1
          style={{
            fontFamily: 'var(--am-font-editorial)',
            fontSize: '1.75rem',
            fontWeight: 700,
            color: 'var(--am-text-primary)',
          }}
        >
          Two-Factor Authentication
        </h1>
        <p style={{ fontSize: '0.875rem', color: 'var(--am-text-secondary)', marginTop: '0.35rem', marginBottom: '1.75rem' }}>
          Enter the 6-digit security code generated by your authenticator app {email ? `for ${email}` : ''}.
        </p>

        {errorMessage && (
          <div className="am-alert am-alert-danger" style={{ textAlign: 'left' }}>
            <AlertCircle size={18} style={{ flexShrink: 0, marginTop: '2px' }} />
            <div>{errorMessage}</div>
          </div>
        )}

        <form onSubmit={handleSubmit}>
          <div className="am-form-group">
            <input
              type="text"
              inputMode="numeric"
              pattern="[0-9]*"
              maxLength={6}
              autoFocus
              className="am-input"
              placeholder="000000"
              value={code}
              onChange={(e) => setCode(e.target.value)}
              style={{
                fontSize: '1.75rem',
                letterSpacing: '0.35em',
                textAlign: 'center',
                padding: '0.75rem',
                fontWeight: 700,
              }}
              required
            />
          </div>

          <button
            type="submit"
            className="am-btn am-btn-primary am-btn-lg"
            style={{ width: '100%', marginTop: '0.5rem' }}
            disabled={submitting}
          >
            {submitting ? 'Verifying Code...' : 'Confirm Authentication'} <ArrowRight size={18} />
          </button>
        </form>

        <p style={{ fontSize: '0.8125rem', color: 'var(--am-text-muted)', marginTop: '1.5rem' }}>
          Time-based One-Time Passwords refresh every 30 seconds.
        </p>
      </div>
    </div>
  );
};
